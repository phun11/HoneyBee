CREATE OR REPLACE VIEW VW_PUBLIC_TRACE AS
SELECT
    p.PRODUCT_ID, p.BATCH_CODE, p.PRODUCT_NAME, p.CATEGORY, p.DESCRIPTION, p.QUALITY_SUMMARY, p.PRICE,
    p.QUANTITY, p.UNIT, p.STATUS AS PRODUCT_STATUS, p.VERSION_NO, p.IMAGE_URL, p.PRODUCT_IMAGE_B64, p.PRODUCT_IMAGE_MIME, p.PICKUP_LOCATION, p.DELIVERY_LOCATION,
    p.REQUIRED_TEMP_MIN, p.REQUIRED_TEMP_MAX, p.REQUIRED_HUMIDITY_MIN, p.REQUIRED_HUMIDITY_MAX,
    p.TRANSPORT_NOTE, p.RECEIVER_NAME, p.RECEIVER_PHONE, p.EXPECTED_DELIVERY_AT,
    p.CREATED_AT AS PRODUCT_CREATED_AT, p.UPDATED_AT AS PRODUCT_UPDATED_AT,
    f.FARM_ID, f.FARM_NAME, f.ADDRESS AS FARM_ADDRESS, f.OWNER_NAME, f.CERTIFICATION, f.CONTACT_PHONE, f.CONTACT_EMAIL,
    s.STORE_ID, s.STORE_NAME, s.ADDRESS AS STORE_ADDRESS, s.PHONE AS STORE_PHONE, s.CONTACT_PERSON AS STORE_CONTACT,
    t.TRANSPORTER_ID, t.TRANSPORTER_NAME,
    o.CULTIVATION_PLACE, o.FARM_ADDRESS AS ORIGIN_FARM_ADDRESS, o.SOWING_DATE, o.HARVEST_DATE, o.EXPIRED_DATE, o.PRODUCTION_PROCESS,
    CASE WHEN o.HARVEST_DATE IS NULL THEN NULL ELSE TRUNC(CURRENT_DATE) - TRUNC(o.HARVEST_DATE) END AS DAYS_AFTER_HARVEST,
    CASE
        WHEN o.EXPIRED_DATE IS NULL THEN NVL(o.FRESHNESS_STATUS, 'UNKNOWN')
        WHEN TRUNC(o.EXPIRED_DATE) < TRUNC(CURRENT_DATE) THEN 'EXPIRED'
        WHEN TRUNC(o.EXPIRED_DATE) - TRUNC(CURRENT_DATE) <= 2 THEN 'NEAR_EXPIRED'
        ELSE NVL(o.FRESHNESS_STATUS, 'FRESH')
    END AS FRESHNESS_STATUS,
    q.QR_TOKEN, q.QR_SIGNATURE, q.QR_URL, q.QR_IMAGE_URL, q.STATUS AS QR_STATUS, q.SALE_STATUS AS QR_SALE_STATUS,
    q.SOLD_AT, q.SOLD_BY_STORE_ID, q.SOLD_NOTE
FROM PRODUCTS p
JOIN FARMS f ON p.FARM_ID = f.FARM_ID
LEFT JOIN STORES s ON p.STORE_ID=s.STORE_ID
LEFT JOIN TRANSPORTERS t ON p.TRANSPORTER_ID=t.TRANSPORTER_ID
LEFT JOIN PRODUCT_ORIGIN o ON p.PRODUCT_ID = o.PRODUCT_ID
LEFT JOIN QR_CODES q ON p.PRODUCT_ID = q.PRODUCT_ID;
