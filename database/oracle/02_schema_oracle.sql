    FILE_URL VARCHAR2(500 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'VALID' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
