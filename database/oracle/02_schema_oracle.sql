CREATE SEQUENCE SEQ_PRODUCTS START WITH 100 INCREMENT BY 1 NOCACHE;

CREATE TABLE FARMS (
    FARM_ID NUMBER(19) PRIMARY KEY,
    FARM_NAME VARCHAR2(150 CHAR) NOT NULL,
    ADDRESS VARCHAR2(255 CHAR) NOT NULL,
    OWNER_NAME VARCHAR2(100 CHAR),
    CERTIFICATION VARCHAR2(100 CHAR),
    CONTACT_PHONE VARCHAR2(20 CHAR),
    CONTACT_EMAIL VARCHAR2(100 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_FARMS_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE TRANSPORTERS (
    TRANSPORTER_ID NUMBER(19) PRIMARY KEY,
    TRANSPORTER_NAME VARCHAR2(150 CHAR) NOT NULL,
    LICENSE_NO VARCHAR2(80 CHAR),
    PHONE VARCHAR2(30 CHAR),
    TEMPERATURE_SUPPORT VARCHAR2(100 CHAR),
    ADDRESS VARCHAR2(255 CHAR),
    CONTACT_PERSON VARCHAR2(100 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_TRANSPORTERS_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE STORES (
    STORE_ID NUMBER(19) PRIMARY KEY,
    STORE_NAME VARCHAR2(150 CHAR) NOT NULL,
    STORE_TYPE VARCHAR2(50 CHAR),
    ADDRESS VARCHAR2(255 CHAR),
    CITY VARCHAR2(80 CHAR),
    PHONE VARCHAR2(30 CHAR),
    CONTACT_PERSON VARCHAR2(100 CHAR),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_STORES_TYPE CHECK (STORE_TYPE IN ('SUPERMARKET','CLEAN_FOOD_STORE','RESTAURANT','OTHER')),
    CONSTRAINT CK_STORES_STATUS CHECK (STATUS IN ('ACTIVE','INACTIVE'))
);

CREATE TABLE USERS (
    USER_ID NUMBER(19) PRIMARY KEY,
    USERNAME VARCHAR2(50 CHAR) NOT NULL UNIQUE,
    PASSWORD VARCHAR2(255 CHAR) NOT NULL,
    FULL_NAME VARCHAR2(100 CHAR),
    EMAIL VARCHAR2(100 CHAR),
    PHONE VARCHAR2(30 CHAR),
    ROLE VARCHAR2(20 CHAR) NOT NULL,
    FARM_ID NUMBER(19),
    TRANSPORTER_ID NUMBER(19),
    STORE_ID NUMBER(19),
    STATUS VARCHAR2(20 CHAR) DEFAULT 'ACTIVE' NOT NULL,
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_USERS_ROLE CHECK (ROLE IN ('ADMIN','FARMER','TRANSPORTER','STORE')),
    CONSTRAINT CK_USERS_STATUS CHECK (STATUS IN ('ACTIVE','LOCKED')),
    CONSTRAINT FK_USERS_FARM FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_USERS_TRANSPORTER FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID),
    CONSTRAINT FK_USERS_STORE FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID)
);


CREATE TABLE STATUS_TRANSITIONS (
    TRANSITION_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FROM_STATUS VARCHAR2(30 CHAR) NOT NULL,
    TO_STATUS VARCHAR2(30 CHAR) NOT NULL,
    ROLE_ALLOWED VARCHAR2(30 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(500 CHAR),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT UQ_STATUS_TRANSITIONS UNIQUE (FROM_STATUS, TO_STATUS, ROLE_ALLOWED)
);

CREATE TABLE PRODUCTS (
    PRODUCT_ID NUMBER(19) PRIMARY KEY,
    FARM_ID NUMBER(19) NOT NULL,
    STORE_ID NUMBER(19),
    TRANSPORTER_ID NUMBER(19),
    BATCH_CODE VARCHAR2(60 CHAR) UNIQUE,
    PRODUCT_NAME VARCHAR2(150 CHAR) NOT NULL,
    CATEGORY VARCHAR2(80 CHAR) NOT NULL,
    DESCRIPTION VARCHAR2(2000 CHAR),
    QUALITY_SUMMARY VARCHAR2(500 CHAR),
    PRICE NUMBER(12,2),
    QUANTITY NUMBER(12,2) DEFAULT 0 NOT NULL,
    UNIT VARCHAR2(20 CHAR) DEFAULT 'kg' NOT NULL,
    STATUS VARCHAR2(30 CHAR) DEFAULT 'CREATED' NOT NULL,
    VERSION_NO NUMBER(19) DEFAULT 0 NOT NULL,
    IMAGE_URL VARCHAR2(500 CHAR),
    PRODUCT_IMAGE_B64 CLOB,
    PRODUCT_IMAGE_MIME VARCHAR2(80 CHAR),
    PICKUP_LOCATION VARCHAR2(255 CHAR),
    DELIVERY_LOCATION VARCHAR2(255 CHAR),
    REQUIRED_TEMP_MIN NUMBER(5,2),
    REQUIRED_TEMP_MAX NUMBER(5,2),
    REQUIRED_HUMIDITY_MIN NUMBER(5,2),
    REQUIRED_HUMIDITY_MAX NUMBER(5,2),
    TRANSPORT_NOTE VARCHAR2(1000 CHAR),
    RECEIVER_NAME VARCHAR2(120 CHAR),
    RECEIVER_PHONE VARCHAR2(30 CHAR),
    EXPECTED_DELIVERY_AT TIMESTAMP,
    CREATED_BY NUMBER(19),
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_PRODUCTS_PRICE CHECK (PRICE IS NULL OR PRICE >= 0),
    CONSTRAINT CK_PRODUCTS_QTY CHECK (QUANTITY >= 0),
    CONSTRAINT CK_PRODUCTS_TEMP CHECK (REQUIRED_TEMP_MIN IS NULL OR REQUIRED_TEMP_MAX IS NULL OR REQUIRED_TEMP_MIN <= REQUIRED_TEMP_MAX),
    CONSTRAINT CK_PRODUCTS_HUMID CHECK (REQUIRED_HUMIDITY_MIN IS NULL OR REQUIRED_HUMIDITY_MAX IS NULL OR REQUIRED_HUMIDITY_MIN <= REQUIRED_HUMIDITY_MAX),
    CONSTRAINT CK_PRODUCTS_STATUS CHECK (STATUS IN (
        'CREATED','FARM_CONFIRMED','WAITING_FOR_PICKUP','PICKED_UP','IN_TRANSIT','ARRIVED_AT_HUB','OUT_FOR_DELIVERY','DELIVERED',
        'STORE_RECEIVED','AVAILABLE_FOR_SALE','RETURN_REQUESTED','RETURNED','CANCELLED','REJECTED','SOLD_OUT','EXPIRED','REVOKED'
    )),
    CONSTRAINT FK_PRODUCTS_FARMS FOREIGN KEY (FARM_ID) REFERENCES FARMS(FARM_ID),
    CONSTRAINT FK_PRODUCTS_STORES FOREIGN KEY (STORE_ID) REFERENCES STORES(STORE_ID),
    CONSTRAINT FK_PRODUCTS_TRANSPORTERS FOREIGN KEY (TRANSPORTER_ID) REFERENCES TRANSPORTERS(TRANSPORTER_ID)
);

CREATE TABLE PRODUCT_ORIGIN (
    ORIGIN_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    PRODUCT_ID NUMBER(19) NOT NULL UNIQUE,
    CULTIVATION_PLACE VARCHAR2(255 CHAR),
    FARM_ADDRESS VARCHAR2(255 CHAR),
    SOWING_DATE DATE,
    HARVEST_DATE DATE,
    EXPIRED_DATE DATE,
    PRODUCTION_PROCESS VARCHAR2(2000 CHAR),
    FRESHNESS_STATUS VARCHAR2(30 CHAR) DEFAULT 'FRESH',
    CREATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UPDATED_AT TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT CK_ORIGIN_DATES CHECK (EXPIRED_DATE IS NULL OR HARVEST_DATE IS NULL OR EXPIRED_DATE >= HARVEST_DATE),
    CONSTRAINT CK_FRESHNESS_STATUS CHECK (FRESHNESS_STATUS IN ('FRESH','NEAR_EXPIRED','EXPIRED','UNKNOWN')),
    CONSTRAINT FK_ORIGIN_PRODUCT FOREIGN KEY (PRODUCT_ID) REFERENCES PRODUCTS(PRODUCT_ID) ON DELETE CASCADE
);

CREATE TABLE CERTIFICATES (
    CERTIFICATE_ID NUMBER(19) GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
    FARM_ID NUMBER(19),
    PRODUCT_ID NUMBER(19),
    CERTIFICATE_NAME VARCHAR2(150 CHAR) NOT NULL,
    ISSUED_BY VARCHAR2(150 CHAR),
